export interface CurrencyOption {
  code: string;
  label: string;
}

export function getCurrencyOptions(locale: string, currentCurrency?: string): CurrencyOption[] {
  const codes = new Set<string>(CURRENCY_CODES);
  const normalizedCurrent = currentCurrency?.trim().toUpperCase();
  if (normalizedCurrent && /^[A-Z]{3}$/.test(normalizedCurrent)) codes.add(normalizedCurrent);

  let names: Intl.DisplayNames | undefined;
  try {
    names = new Intl.DisplayNames([locale], { type: 'currency' });
  } catch {
    // An unsupported runtime locale must not make settings unusable.
  }

  return [...codes].sort().map((code) => {
    const name = names?.of(code);
    return { code, label: name && name !== code ? `${code} — ${name}` : code };
  });
}
