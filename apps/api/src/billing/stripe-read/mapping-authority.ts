/** What the registry needs to know about a stored proof to honour a TEST_MODE_VERIFIED entry. */
export interface ProofLookup { get(proofId: string): Readonly<{ captureOrigin: string; methodId: string; apiVersion: string }> | null }

export class MappingRegistry {
  private constructor(private readonly list: readonly FieldMapping[], readonly downgraded: readonly string[]) {}

  /** The built-in catalog: every mapping SDK_SCHEMA_UNPROVEN_LIVE (or UNSUPPORTED). */
  static catalog(): MappingRegistry { return new MappingRegistry(DEFAULT_MAPPING_CATALOG, []); }

  /**
   * Loads persisted mapping state. A TEST_MODE_VERIFIED entry is honoured ONLY if `proofs` can produce the proof it names and that proof is a REAL_NETWORK capture of the same operation and API version;
   * otherwise it is loaded as SDK_SCHEMA_UNPROVEN_LIVE and listed in `downgraded`. Malformed entries make the whole load fail (null).
   */
  static load(entries: unknown, proofs: ProofLookup | null = null): MappingRegistry | null {
    if (!Array.isArray(entries)) return null;
    const out: FieldMapping[] = []; const downgraded: string[] = []; const seen = new Set<string>();
    const STATUSES = ['SDK_SCHEMA_UNPROVEN_LIVE', 'TEST_MODE_VERIFIED', 'UNSUPPORTED', 'SCHEMA_DRIFT'];
    for (const e of entries as Array<Record<string, unknown>>) {
      if (!e || typeof e !== 'object' || typeof e.apiVersion !== 'string' || typeof e.sourceField !== 'string' || typeof e.sourceOperation !== 'string' || !Object.prototype.hasOwnProperty.call(READ_METHODS, e.sourceOperation) ||
          typeof e.status !== 'string' || !STATUSES.includes(e.status) || e.contractVersion !== MAPPING_CONTRACT_VERSION || typeof e.destination !== 'string' || typeof e.nullable !== 'boolean') return null;
      const key = `${e.apiVersion}|${e.sourceOperation}|${e.sourceField}`;
      if (seen.has(key)) return null; seen.add(key);
      let status = e.status as MappingVerification; let proofId = typeof e.verifiedByProofId === 'string' ? e.verifiedByProofId : null;
      if (status === 'TEST_MODE_VERIFIED') {
        const p = proofId && proofs ? proofs.get(proofId) : null;
        if (!p || p.captureOrigin !== 'REAL_NETWORK' || p.methodId !== e.sourceOperation || p.apiVersion !== e.apiVersion) { status = 'SDK_SCHEMA_UNPROVEN_LIVE'; proofId = null; downgraded.push(key); }
      } else proofId = null;
      out.push(Object.freeze({ ...(e as unknown as FieldMapping), status, verifiedByProofId: proofId }));
    }
    return new MappingRegistry(Object.freeze(out), Object.freeze(downgraded));
  }

  entries(): readonly FieldMapping[] { return this.list; }
  for(op: ReadMethodId, apiVersion: string): readonly FieldMapping[] { return this.list.filter(x => x.sourceOperation === op && x.apiVersion === apiVersion); }

  /** The status of an OPERATION: SCHEMA_DRIFT if any field drifted; UNPROVEN if any field is unproven; VERIFIED only if every supportable field is; UNSUPPORTED when nothing is mapped or everything is unsupported. */
  operationStatus(op: ReadMethodId, apiVersion: string): MappingVerification {
    const ms = this.for(op, apiVersion).filter(x => x.status !== 'UNSUPPORTED');
    if (ms.length === 0) return 'UNSUPPORTED';
    if (ms.some(x => x.status === 'SCHEMA_DRIFT')) return 'SCHEMA_DRIFT';
    if (ms.some(x => x.status === 'SDK_SCHEMA_UNPROVEN_LIVE')) return 'SDK_SCHEMA_UNPROVEN_LIVE';
    return 'TEST_MODE_VERIFIED';
  }

  /** Internal to the proof module: a copy with some entries replaced. Not exported from the package index. */
  replace(updates: ReadonlyMap<string, Pick<FieldMapping, 'status' | 'verifiedByProofId'>>): MappingRegistry {
    return new MappingRegistry(Object.freeze(this.list.map(x => { const u = updates.get(`${x.apiVersion}|${x.sourceOperation}|${x.sourceField}`); return u ? Object.freeze({ ...x, ...u }) : x; })), this.downgraded);
  }
}
export const mappingKey = (x: Pick<FieldMapping, 'apiVersion' | 'sourceOperation' | 'sourceField'>) => `${x.apiVersion}|${x.sourceOperation}|${x.sourceField}`;

// ---- structural observation and compatibility -------------------------------------------------------------------------------------------------------------------------------------------------

export type Compatibility = 'COMPATIBLE' | 'ABSENT' | 'TYPE_MISMATCH' | 'ENUM_UNKNOWN';
export interface PathObservation { readonly types: readonly string[]; readonly enumValues: readonly string[]; readonly instances: number }
export interface ShapeObservation { readonly observations: Readonly<Record<string, PathObservation>>; readonly unmappedPaths: readonly string[] }
export interface CompatibilityResult { readonly sourceField: string; readonly result: Compatibility }

const typeOf = (v: unknown): string => (v === null ? 'null' : Array.isArray(v) ? 'list' : typeof v === 'number' ? (Number.isSafeInteger(v) ? 'integer' : 'number') : typeof v);
function collect(root: unknown, tokens: readonly string[]): Array<{ present: boolean; value?: unknown }> {
  if (tokens.length === 0) return [{ present: true, value: root }];
  const [head, ...rest] = tokens;
  const list = head!.endsWith('[]'); const key = list ? head!.slice(0, -2) : head!;
  if (root === null || typeof root !== 'object' || Array.isArray(root) || !Object.prototype.hasOwnProperty.call(root, key)) return [{ present: false }];
  const next = (root as Record<string, unknown>)[key];
  if (!list) return collect(next, rest);
  if (!Array.isArray(next)) return [{ present: false }];
  return next.flatMap(item => collect(item, rest));
}

/** Evaluates ONE response body against the mappings of its operation. The shape keeps types and the values of ENUM-typed fields only; no id, amount, name or metadata is retained. */
export function observeShape(body: unknown, mappings: readonly FieldMapping[]): ShapeObservation {
  const observations: Record<string, PathObservation> = {};
  for (const mp of mappings) {
    if (mp.status === 'UNSUPPORTED') continue;
    const hits = collect(body, mp.sourceField.split('.')).filter(h => h.present);
    const types = [...new Set(hits.map(h => (mp.expectedType === 'ref' && h.value !== null && typeof h.value === 'object' && typeof (h.value as { id?: unknown }).id === 'string' ? 'ref' : typeOf(h.value))))].sort();
    const isEnum = typeof mp.expectedType === 'object';
    const enumValues = isEnum ? [...new Set(hits.map(h => h.value).filter((x): x is string => typeof x === 'string'))].sort() : [];
    observations[mp.sourceField] = Object.freeze({ types: Object.freeze(types), enumValues: Object.freeze(enumValues), instances: hits.length });
  }
  const covered = mappings.map(x => x.sourceField.replace(/\[\]/g, '').split('.'));
  const unmapped: string[] = [];
  const walk = (v: unknown, path: string[]) => {
    if (unmapped.length >= 200 || path.length > 4 || v === null || typeof v !== 'object') return;
    if (Array.isArray(v)) { for (const x of v.slice(0, 3)) walk(x, path); return; }
    for (const k of Object.keys(v as object)) {
      const p = [...path, k];
      if (k === 'metadata') continue; // customer-defined keys are never recorded
      if (!covered.some(c => c.length >= p.length && p.every((s, i) => c[i] === s))) { unmapped.push(p.join('.')); continue; }
      walk((v as Record<string, unknown>)[k], p);
    }
  };
  walk(body, []);
  return Object.freeze({ observations: Object.freeze(observations), unmappedPaths: Object.freeze([...new Set(unmapped)].sort()) });
}

export function evaluateCompatibility(shape: ShapeObservation, mappings: readonly FieldMapping[]): readonly CompatibilityResult[] {
  return mappings.filter(x => x.status !== 'UNSUPPORTED').map(mp => {
    const o = shape.observations[mp.sourceField];
    if (!o || o.instances === 0) return { sourceField: mp.sourceField, result: 'ABSENT' as const };
    const allowed = (t: string) => {
      if (t === 'null') return mp.nullable;
      if (typeof mp.expectedType === 'object') return t === 'string';
      if (mp.expectedType === 'ref') return t === 'string' || t === 'ref';
      return t === mp.expectedType;
    };
    if (!o.types.every(allowed)) return { sourceField: mp.sourceField, result: 'TYPE_MISMATCH' as const };
    if (typeof mp.expectedType === 'object' && o.enumValues.some(v => !(mp.expectedType as { enum: readonly string[] }).enum.includes(v))) return { sourceField: mp.sourceField, result: 'ENUM_UNKNOWN' as const };
    return { sourceField: mp.sourceField, result: 'COMPATIBLE' as const };
  });
}
