import { READ_METHODS, type ReadMethodId } from './capability-registry';

/**
 * S08-D1D3-DEV-09: the FIELD-MAPPING AUTHORITY. Every provider field the normalizers read is listed here with the operation it comes from, its path, expected type, where it goes, what completeness it
 * needs, the API version it is defined for and its VERIFICATION STATUS:
 *
 *   SDK_SCHEMA_UNPROVEN_LIVE  the field exists with this name and type in the Stripe SDK type definitions locked in this repository. Nothing more is claimed.
 *   TEST_MODE_VERIFIED        a real, attributable, authorized test-mode response showed this field with this type (see proof-capture.ts). The ONLY way to reach it is a proof captured over the real network.
 *   UNSUPPORTED               no source-supported provider field exists (for example the idempotency key of a line's parent item). The fact stays UNRESOLVED.
 *   SCHEMA_DRIFT              a real response disagreed with the mapping (wrong type or an enum value we do not know).
 *
 * A synthetic fixture, a mock proof, an injected transport or a response that merely matches never raises a status. Status is data; changing it is an operation of the proof module, not of a caller.
 */
export const MAPPING_CONTRACT_VERSION = 'S08-STRIPE-MAPPING/1' as const;
export type MappingVerification = 'SDK_SCHEMA_UNPROVEN_LIVE' | 'TEST_MODE_VERIFIED' | 'UNSUPPORTED' | 'SCHEMA_DRIFT';
export type ExpectedType = 'string' | 'integer' | 'boolean' | 'object' | 'list' | 'ref' | Readonly<{ enum: readonly string[] }>;

export interface FieldMapping {
  readonly apiVersion: string;
  readonly sourceOperation: ReadMethodId;
  /** Dotted path in the response; `[]` iterates a list (`data[].id`). */
  readonly sourceField: string;
  readonly expectedType: ExpectedType;
  readonly nullable: boolean;
  /** The normalized fact this field feeds. */
  readonly destination: string;
  /** What must hold for the destination fact to be established from it. */
  readonly completeness: string;
  readonly contractVersion: typeof MAPPING_CONTRACT_VERSION;
  readonly status: MappingVerification;
  readonly verifiedByProofId: string | null;
  readonly note: string | null;
}

const V = '2026-05-27.dahlia';
const m = (sourceOperation: ReadMethodId, sourceField: string, expectedType: ExpectedType, destination: string, o: { nullable?: boolean; completeness?: string; status?: MappingVerification; note?: string } = {}): FieldMapping =>
  Object.freeze({ apiVersion: V, sourceOperation, sourceField, expectedType, nullable: o.nullable ?? false, destination, completeness: o.completeness ?? 'present and of the expected type on every item', contractVersion: MAPPING_CONTRACT_VERSION,
    status: o.status ?? 'SDK_SCHEMA_UNPROVEN_LIVE', verifiedByProofId: null, note: o.note ?? null });
const en = (...values: string[]): ExpectedType => ({ enum: Object.freeze(values) });

